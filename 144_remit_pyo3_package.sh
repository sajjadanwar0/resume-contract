    // across stray/extra resumes.
    let gated = sh
        .effects
        .get(&(BranchKey::root(), INTERRUPT_TASK))
        .copied()
        .unwrap_or(0);
    assert!(gated <= 1, "CO violated: gated effect fired {gated} times on root");
