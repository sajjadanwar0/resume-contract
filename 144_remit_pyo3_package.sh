                    m.sh.consumed = true;
                    m.sh.consumed_val = Some(v.to_string());
                    assert_eq!(m.p.outcome(&branch), Some(v));
                }
                other => panic!("first consume must serve supplied, got {other:?}"),
            }
            out.push(m);
        }
    }
