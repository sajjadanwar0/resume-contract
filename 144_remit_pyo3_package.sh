/// Shadow of the TLA+ variables, kept independent of the core.
#[derive(Clone, Default)]
struct Shadow {
    effects: std::collections::HashMap<(BranchKey, TaskId), u32>,
    interrupted: bool,
    consumed: bool,
    consumed_val: Option<String>,
    fork_vals: Vec<String>,
    fork_outs: Vec<String>,
